package homework2;

import java.util.Scanner;

public class WhileForLoops {
    Scanner scan = new Scanner(System.in);

    /*Задача 1:
    Напишите программу, которая будет принимать на вход число из консоли и на выход
    будет выводить сообщение четное число или нет. Для определения четности числа
    используйте операцию получения остатка от деления (операция выглядит так: '% 2').
     */
    public void task8() {
        System.out.print("Введите любое целое число: ");
        int number = scan.nextInt();
        if (number % 2 == 0) {
            System.out.println("Вы ввели четное число " + number);
        } else {
            System.out.println("Вы ввели нечетное число");
        }

    }

    /*Задача 2:
    Для введенного числа t (температура на улице) вывести: Если t>–5, то вывести «Warm».
    Если –5>= t > –20, то вывести «Normal». Если –20>= t, то вывести «Cold».
     */
    public void task9() {
        System.out.print("Введите температуру на улице: ");
        int t = scan.nextInt();
        if (t > -5) {
            System.out.println("Warm");
        } else if (t <= -5 && t >= -20) {
            System.out.println("Normal");
        } else {
            System.out.println("Cold");
        }
    }

    /*Задача 3:
    Составьте программу, выводящую на экран квадраты чисел от 10 до 20 включительно.
     */
    public void task10() {
        System.out.println("Квадраты чисел от 10 до 20:");
        // Инициализируем переменную-счетчик
        int i = 10;
        // Цикл while выполняется пока условие истинно
        while (i <= 20) {
            // Выводим число и его квадрат (вычисляем в момент вывода)
            System.out.println(i + "² = " + (i * i));
            // Увеличиваем счетчик на 1
            i++;
        }
    }

    /*Задача 4:
    Необходимо, чтоб программа выводила на экран вот такую последовательность:
    7 14 21 28 35 42 49 56 63 70 77 84 91 98. В решении используйте цикл while.
    */
    public void task11() {
        System.out.print("Последовательность чисел от 7 до 98: ");
        // Инициализируем переменную-счетчик
        int i = 7;
        // Цикл while выполняется пока условие истинно
        while (i <= 98) {
            System.out.print(i + " ");
            i = i + 7;
        }
    }

    /*Задача *:
    Напишите программу, где пользователь вводит любое целое положительное число. А
    программа суммирует все числа от 1 до введенного пользователем числа. Для ввода
    числа воспользуйтесь классом Scanner. Сделать проверку, чтобы пользователь не мог
    ввести некорректные данные.
     */
    public void task12() {
        int number = 0;
        boolean isValidInput = false;
        System.out.println("\nВведите целое положительное число: ");
        while (!isValidInput) {
            // Проверяем, ввел ли пользователь корректное целое число
            if (scan.hasNextInt()) {
                number = scan.nextInt();
                // Проверяем, что число положительное
                if (number > 0) {
                    isValidInput = true; // Выходим из цикла, если введено корректное положительное число
                } else {
                    System.out.println("Ошибка: введены некорректные данные. Пожалуйста, введите целое положительное число.");
                }
            } else {
                System.out.println("Ошибка: введены некорректные данные. Пожалуйста, введите целое положительное число.");
                scan.next();
            }
        }
        // Суммируем все числа от 1 до введенного пользователем числа
        int sum = 0;
        for (int i = 1; i <= number; i++) {
            sum += i; // sum=sum+1
        }
        // Выводим результат
        System.out.println("Сумма всех чисел от 1 до " + number + " равна " + sum + ".");
        // scan.close(); // Закрываем сканер
    }
}
