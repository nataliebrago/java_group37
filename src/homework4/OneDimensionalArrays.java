    public void findMinMaxIndices() {
        int[] array = initArray(100);
        // Проверка, что массив не null и не пустой
        if (array.length == 0) {
            System.out.println("Массив пустой или не инициализирован");
            return; // Выход из метода, если массив некорректен
        }

        // Инициализация переменных для хранения индексов минимального и максимального элементов
        int minIndex = 0; // Предполагаем, что минимальный элемент в начале массива
        int maxIndex = 0; // Аналогично для максимального элемента

        // Проходим по всему массиву, начиная со второго элемента (индекс 1)
        for (int i = 1; i < array.length; i++) {
            // Если текущий элемент меньше текущего минимального
            if (array[i] < array[minIndex]) {
                minIndex = i; // Обновляем индекс минимального элемента
            }
            // Если текущий элемент больше текущего максимального
            if (array[i] > array[maxIndex]) {
                maxIndex = i; // Обновляем индекс максимального элемента
            }
        }

        // Выводим в консоль индексы найденных элементов
        System.out.println("Индекс минимального элемента: " + minIndex);
        System.out.println("Индекс максимального элемента: " + maxIndex);
    }

