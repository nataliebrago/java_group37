    public void countZeroElements() {
        int[] array = initArray(100);
        int zeroCount = 0; // переменная для подсчёта нулевых элементов

        // Проходим по всему массиву
        for (int i = 0; i < array.length; i++) {
            if (array[i] == 0) { // если текущий элемент равен нулю
                zeroCount++; // увеличиваем счётчик нулевых элементов
            }
        }

        // Проверяем, есть ли нулевые элементы
        if (zeroCount > 0) {
            System.out.println("Количество нулевых элементов: " + zeroCount);
        } else {
            System.out.println("Нулевых элементов в массиве нет");
        }
    }

