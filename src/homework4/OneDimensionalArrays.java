    private int[] initArray(int bound) {
        System.out.println("Введите любое целое число: ");
        int number = scan.nextInt(); // Чтение целого числа с клавиатуры и сохранение в переменную number
        int[] array = new int[number]; // Создание массива целых чисел

        // Выбор способа заполнения
        System.out.println("Выберите способ заполнения:");
        System.out.println("1 - случайными числами");
        System.out.println("2 - вручную");
        System.out.print("Введите 1 или 2: ");

        int choice = scan.nextInt(); // Чтение выбора пользователя (1 или 2)
        if (choice == 1) { // Проверка, если пользователь выбрал вариант 1 (случайные числа)
            // Заполнение случайными числами
            for (int i = 0; i < number; i++) { /*Цикл for для заполнения массива:
                int i = 0 - инициализация счетчика
                i < number - условие продолжения цикла
                i++ - увеличение счетчика на каждой итерации
                */
                array[i] = random.nextInt(bound); //Заполнение текущего элемента массива случайным числом от 0 до 99
                System.out.print(array[i] + " ");
            }
            System.out.println(); // для разделения вывода

        } else if (choice == 2) { // Проверка, если пользователь выбрал вариант 2 (ручной ввод)
            // Ввод элементов вручную
            for (int i = 0; i < number; i++) {
                System.out.print("Введите элемент " + (i + 1) + ": ");
                array[i] = scan.nextInt();
            }
        } else {
            System.out.println("Некорректный ввод. Попробуйте еще раз");
            initArray(100);
        }
        return array;
    }

