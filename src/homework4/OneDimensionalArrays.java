    private int[] addOne(int[] array) {
        int n = array.length; //Получение длины массива, чтобы знать, с какого индекса начинать обработку
        // Проходим с конца массива
        for (int i = n - 1; i >= 0; i--) { // Проходим по массиву с конца к началу, начиная с последнего элемента.
            if (array[i] < 9) {
                // Если текущая цифра меньше 9, просто увеличиваем её
                array[i]++;
                return array;  //После увеличения возвращаем результат
            } else {
                // Если цифра 9, она становится 0, переносим 1 в следующий разряд
                array[i] = 0;
            }
        }
        int[] newNumber = new int[n + 1];
        newNumber[0] = 1; // самый старший разряд
        return newNumber;
    }
