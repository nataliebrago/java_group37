    public void reverseArray() {
        int[] array = initArray(100);
        int i = 0; // указатель на начало массива
        int j = array.length - 1; // указатель на конец массива

        while (i < j) { // пока указатели не пересекутся
            // обмен элементов3
            int temp = array[i]; // временно сохраняем элемент с позиции i
            array[i] = array[j]; // присваиваем элемент с позиции j в позицию i
            array[j] = temp; // вставляем сохранённый элемент в позицию j

            i++; // сдвигаем указатель i вперёд
            j--; // сдвигаем указатель j назад
        }
    }

    public boolean isIncreasingSequence() {
        int[] array = initArray(100);
        // Проходим по массиву, начиная со второго элемента
        for (int i = 1; i < array.length; i++) {
            // Если текущий элемент не больше предыдущего
            if (array[i] <= array[i - 1]) {
                System.out.println("Последовательность не возрастает");
                return false; // последовательность не возрастает
            }
        }
        // Если цикл завершился без возврата false, последовательность возрастает
        System.out.println("Последовательность возрастает");
        return true;
    }

